# scanners with gen_penny_variants.py, checks each is byte-identical to the
# locally tested file (SHA-256), adds them to the 06:00 schedule and commits.
import hashlib, subprocess, sys

EXPECTED = {
    "daily_penny_ma_support_ema21_sma50_v1.py":   "cf6ae9d383699eabba6ff8736071004257615b27075bb74d4910c78c75ce3d7f",
    "daily_penny_liquidity_sweep_breakout_v1.py": "3378f95d45765c419fbee770244e04ad713ac40e61e74cd890993cf86a3d4cc1",
}
subprocess.check_call([sys.executable, "claude_run/tools/gen_penny_variants.py", "."])
for f, want in EXPECTED.items():
    h = hashlib.sha256(open(f, "rb").read()).hexdigest()
    print(f, h)
    if h != want:
        sys.exit(f"❌ {f} differs from the tested one — nothing committed")
sched = open("claude_run/schedule.txt").read().rstrip("\n")
for f in EXPECTED:
    if f not in sched:
        sched += "\n" + f
        print(f"✅ added {f} to claude_run/schedule.txt")
open("claude_run/schedule.txt", "w").write(sched + "\n")

